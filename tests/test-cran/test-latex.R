library(testit)

assert('font_ext() handles spaces in font names correctly', {
  # Issue #478: font names with spaces should have spaces replaced with \s*
  (font_ext("Noto Emoji") %==% 'Noto\\s*Emoji(-(Bold|Italic|Regular).*)?[.](tfm|afm|mf|otf|ttf)')
  (font_ext("DejaVu Sans") %==% 'DejaVu\\s*Sans(-(Bold|Italic|Regular).*)?[.](tfm|afm|mf|otf|ttf)')
  # Font names without spaces should work as before
  (font_ext("FandolSong-Regular") %==% 'FandolSong-Regular(-(Bold|Italic|Regular).*)?[.](tfm|afm|mf|otf|ttf)')
})

assert('detect_files() can detect filenames from LaTeX log', {
  # Fonts are also tested in test-tlmgr.R
  (detect_files("! Font U/psy/m/n/10=psyr at 10.0pt not loadable: Metric (TFM) file not found") %==% font_ext("psyr"))
  (detect_files('! The font "FandolSong-Regular" cannot be found.') %==% font_ext("FandolSong-Regular"))
  (detect_files('!pdfTeX error: /usr/local/bin/pdflatex (file tcrm0700): Font tcrm0700 at 600 not found') %==% font_ext('tcrm0700'))
  (detect_files('(fontspec)                The font "LibertinusSerif-Regular" cannot be') %==% font_ext('LibertinusSerif-Regular'))
  (detect_files('! Font \\JY3/mc/m/n/10=file:HaranoAjiMincho-Regular.otf:-kern;jfm=ujis at 9.24713pt not loadable: metric data not found or bad.') %==% 'HaranoAjiMincho-Regular.otf')
  # Fonts with spaces in names (issue #478)
  (detect_files('! The font "Noto Emoji" cannot be found.') %==% font_ext("Noto Emoji"))
  (detect_files('! The font "DejaVu Sans" cannot be found.') %==% font_ext("DejaVu Sans"))

  (length(detect_files("asdf qwer")) == 0)
  (detect_files("! LaTeX Error: File `framed.sty' not found.") %==% 'framed.sty')
  (detect_files("/usr/local/bin/mktexpk: line 123: mf: command not found") %==% 'mf')
  (detect_files("or the language definition file ngerman.ldf was not found") %==% 'ngerman.ldf')
  (detect_files("! Package babel Error: Unknown option 'english'.") %==% 'english.ldf')
  (detect_files("!pdfTeX error: pdflatex (file 8r.enc): cannot open encoding file for reading") %==% '8r.enc')
  (detect_files("! CTeX fontset `fandol' is unavailable in current mode") %==% 'fandol')
  (detect_files('Package widetext error: Install the flushend package which is a part of sttools') %==% 'flushend.sty')
  (detect_files('! Package isodate.sty Error: Package file substr.sty not found.') %==% 'substr.sty')
  (detect_files("! Package fontenc Error: Encoding file `t2aenc.def' not found.") %==% 't2aenc.def')
  (detect_files("! I can't find file `hyph-de-1901.ec.tex'.") %==% 'hyph-de-1901.ec.tex')
  (detect_files("luaotfload-features.lua:835: module 'lua-uni-normalize' not found:") %==% 'lua-uni-algos.lua')
  # PDF standard support packages (latex-lab and colorprofiles)
  (detect_files("No support files for \\DocumentMetadata found.") %==% 'latex-lab')
  (detect_files("(pdf backend): cannot open file for embedding") %==% 'colorprofiles.sty')
})

assert('hyphen_pkgs() maps babel/polyglossia language names to hyphen-* packages', {
  (hyphen_pkgs('french') %==% 'hyphen-french')
  (hyphen_pkgs("`hungarian'") %==% 'hyphen-hungarian')
  (hyphen_pkgs('German (new orthography)') %==% 'hyphen-german')
  (hyphen_pkgs('British English') %==% 'hyphen-english')
  (hyphen_pkgs('pinyin') %==% 'hyphen-chinese')
  (hyphen_pkgs(c('ngerman', 'swissgerman', 'german')) %==% 'hyphen-german')
  (hyphen_pkgs('nynorsk') %==% 'hyphen-norwegian')
  # all Indic languages are in a single package
  (hyphen_pkgs(c('hindi', 'tamil', 'bengali', 'Panjabi')) %==% 'hyphen-indic')
  (hyphen_pkgs(c(
    'assamese', 'bengali', 'gujarati', 'hindi', 'kannada', 'malayalam',
    'marathi', 'oriya', 'pali', 'panjabi', 'tamil', 'telugu'
  )) %==% 'hyphen-indic')
  # older names that are synonyms of other languages
  (hyphen_pkgs(c('amharic', 'geez')) %==% 'hyphen-ethiopic')
  (hyphen_pkgs('persian') %==% 'hyphen-farsi')
  (hyphen_pkgs(c('patois', 'francais', 'french')) %==% 'hyphen-french')
  (hyphen_pkgs(c('polygreek', 'monogreek', 'greek')) %==% 'hyphen-greek')
  (hyphen_pkgs('portuges') %==% 'hyphen-portuguese')
  (hyphen_pkgs('slovene') %==% 'hyphen-slovenian')
  (hyphen_pkgs('espanol') %==% 'hyphen-spanish')
  # names in language.dat may be in mixed case
  (hyphen_pkgs('UKenglish') %==% 'hyphen-english')
  # the pinned German patterns are not in a hyphen-* package
  (hyphen_pkgs('ngerman-x-latest') %==% 'dehyph-exptl')
  (hyphen_pkgs(c('german-x-2024-02-28', 'ngerman-x-2024-02-28', 'german-x-latest')) %==% 'dehyph-exptl')
})

assert('.hyphen_map (generated by tools/update-hyphen.R) is well-formed', {
  m = tinytex:::.hyphen_map
  (is.character(m) && length(m) > 0 && !anyNA(m))
  (all(grepl('^[a-z0-9-]+$', names(m))))
  (all(grepl('^[a-z0-9-]+$', m)))
  (!anyDuplicated(names(m)))
  # only exceptions to hyphen-<name> should be listed
  (all(m != paste0('hyphen-', names(m))))
})

assert('hyphen_pkgs() drops names that are not valid package names', {
  # names come from the log, and they must not be interpreted by the shell
  (hyphen_pkgs('ngerman;id') %==% character())
  (hyphen_pkgs('$(id)') %==% character())
  (hyphen_pkgs('a|b') %==% character())
  (hyphen_pkgs('a&b') %==% character())
  (hyphen_pkgs('--repository=x') %==% character())
  (hyphen_pkgs(character()) %==% character())
  # valid names are kept
  (hyphen_pkgs(c('french', 'x;id', 'swissgerman')) %==% c('hyphen-french', 'hyphen-german'))
  # nothing to install, so tlmgr must not be called (and no rerun is needed)
  (detect_hyphen("! Package babel Error: You haven't defined the language 'x;id' yet.") %==% character())
  (!check_babel("Package babel Warning: No hyphenation patterns were preloaded for the language `x;id'."))
  (!check_polyglossia("Package polyglossia Warning: No hyphenation patterns were loaded for `x;id'"))
})

assert('missing hyphenation patterns are detected from babel errors (#515)', {
  x = c(
    "! Package babel Error: You haven't defined the language 'ngerman' yet.",
    "(babel)                Perhaps you misspelled it or your installation",
    "(babel)                is not complete."
  )
  (detect_hyphen(x) %==% 'hyphen-german')
  (detect_hyphen("! Package babel Error: You haven't defined the language `french' yet.") %==% 'hyphen-french')
  (detect_hyphen("! Package babel Error: Unknown option 'ngerman'.") %==% character())
  # the error is not about a missing file, so no tlmgr search is needed
  (length(detect_files(x)) == 0)
  (parse_packages(text = x, quiet = rep(TRUE, 3)) %==% 'hyphen-german')
})

